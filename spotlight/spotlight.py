# --- searching --------------------------------------------------------------------
def elephant(provider, query, limit):
    """Results of one Elephant provider as a list of dicts."""
    try:
        out = subprocess.run(["elephant", "query", "--json", f"{provider};{query};{limit}"],
                             capture_output=True, text=True, timeout=3).stdout
    except (OSError, subprocess.TimeoutExpired):
        return []
    items = []
    for line in out.splitlines():
        try:
            items.append(json.loads(line)["item"])
        except (ValueError, KeyError):
            pass
    return items[:limit]


def search_section(sec, query):
    """Rows for one section: list of dicts {title, subtitle, icon, action, alt}."""
    kind, limit = sec["kind"], int(sec.get("limit", 5))
    q = query.strip()

    if kind == "web":
        if not q:
            return []
        engine, term = None, q
        head, _, rest = q.partition(" ")
        for e in ENGINES:                       # "map paris", "yt lofi"…
            if e.get("prefix") and head == e["prefix"] and rest:
                engine, term = e, rest
        engines = [engine] if engine else [e for e in ENGINES if e.get("default")] or ENGINES[:2]
        rows = []
        for e in engines[:limit]:
            url = e["url"].replace("%TERM%", urllib.parse.quote_plus(term))
            is_map = "map" in e.get("name", "").lower()
            rows.append({"title": f"{term}", "icon": e.get("icon") or "web-browser",
                         "subtitle": f"Show on {e['name']}" if is_map else f"Search with {e['name']}",
                         "action": ("uri", url)})
        return rows

    if kind == "run":
        cmd = q.split()[0] if q else ""
        if not cmd or not shutil.which(cmd):
            return []
        return [{"title": q, "subtitle": "Run command · Shift+Enter: in a terminal",
                 "icon": "utilities-terminal", "action": ("sh", q), "alt": ("term", q)}]

    if kind == "apps" and not q:
        limit = max(limit, 8)                   # empty query: a few apps
    if not q and not (kind == "apps" or (kind in ("clipboard", "emoji") and sec.get("via_prefix"))):
        return []

    rows = []
    for it in elephant(sec["provider"], q, limit):
        text, sub = (it.get("text") or "").strip(), (it.get("subtext") or "")
        if kind == "calc":
            if not text or text == q or not any(c.isdigit() for c in q):
                continue
            rows.append({"title": f"= {text}", "subtitle": f"{q} · Enter to copy",
                         "icon": "accessories-calculator", "action": ("copy", text)})
            break
        if kind == "apps":
            rows.append({"title": text, "subtitle": "" if sub == text else sub,
                         "icon": it.get("icon") or "application-x-executable",
                         "action": ("app", it.get("identifier", ""))})
        elif kind == "actions":
            if text in MENU_CMDS:
                rows.append({"title": text, "subtitle": "Desktop action",
                             "icon": it.get("icon") or "preferences-system", "action": ("sh", MENU_CMDS[text])})
        elif kind == "files":
            path = text.rstrip("/") or text
            is_dir = text.endswith("/")
            home = os.path.expanduser("~")
            pretty = os.path.dirname(path).replace(home, "~", 1)
            rows.append({"title": os.path.basename(path) or path, "subtitle": pretty,
                         "icon": "folder" if is_dir else file_icon(path),
                         "action": ("uri", Gio.File.new_for_path(path).get_uri()),
                         "alt": ("uri", Gio.File.new_for_path(os.path.dirname(path)).get_uri())})
        elif kind == "clipboard":
            if it.get("preview_type") not in (None, "text"):
                continue                        # images: use Walker (SUPER+V)
            one = " ".join(text.split())
            if one:
                rows.append({"title": one[:120], "subtitle": f"{ago(sub)} · Enter to copy",
                             "icon": "edit-paste", "action": ("copy", text)})
        elif kind == "emoji":
            glyph = it.get("icon") or ""
            if glyph:
                rows.append({"title": text, "glyph": glyph,
                             "subtitle": "Enter: insert · Shift+Enter: copy only",
                             "action": ("emoji", glyph), "alt": ("copy", glyph)})
    return rows[:limit]


def ago(stamp):
    """'Thu, 08 Oct 2026 19:26:47 +0200' -> '5 min ago'."""
    from email.utils import parsedate_to_datetime
    import datetime
    try:
        delta = datetime.datetime.now(datetime.timezone.utc) - parsedate_to_datetime(stamp)
    except (TypeError, ValueError):
        return stamp or ""
    s = int(delta.total_seconds())
    for unit, size in (("d", 86400), ("h", 3600), ("min", 60)):
        if s >= size:
            return f"{s // size} {unit} ago"
    return "just now"


def file_icon(path):
    ctype, _ = Gio.content_type_guess(path, None)
    icon = Gio.content_type_get_icon(ctype)
    names = icon.get_names() if hasattr(icon, "get_names") else []
    theme = Gtk.IconTheme.get_for_display(Gdk.Display.get_default())
    for n in names:
        if theme.has_icon(n):
            return n
    return "text-x-generic"


# --- launching -----------------------------------------------------------------------
def spawn(argv):
    subprocess.Popen(argv, start_new_session=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def run_action(action):
    kind, value = action
    if kind == "app":
        info = Gio.DesktopAppInfo.new(value)
        if info:
            ctx = Gdk.Display.get_default().get_app_launch_context()
            ctx.unsetenv("LD_PRELOAD")           # belt and braces, see top of file
            info.launch([], ctx)
        else:
            spawn(["gtk-launch", value.removesuffix(".desktop")])
    elif kind == "uri":
        spawn(["xdg-open", value])
    elif kind == "copy":
        p = subprocess.Popen(["wl-copy"], stdin=subprocess.PIPE, start_new_session=True)
        p.communicate(value.encode())
    elif kind == "emoji":
        run_action(("copy", value))
        if shutil.which("wtype"):              # type it into the window below
            spawn(["sh", "-c", f"sleep 0.25; wtype {json.dumps(value)}"])
    elif kind == "sh":
        spawn(["sh", "-c", value])
    elif kind == "term":
        term = os.environ.get("TERMINAL", "kitty")
        spawn(["sh", "-c", f'{term} -e sh -c {json.dumps(value + "; exec $SHELL")}'])


