#!/usr/bin/env python3
# =============================================================================
#  spotlight/spotlight.py — sectioned Spotlight launcher (GTK 4 + layer-shell)
# =============================================================================
#  One list of results, grouped by kind with a small titled separator between
#  each group (Calculator, Applications, Desktop actions, Files, Emoji,
#  Clipboard, Web & maps, Command). Searching is delegated to Elephant (the backend of Walker), so
#  ranking/indexing is shared with Walker; launching is done here.
#
#  Config : spotlight/config.toml   (sections, order, limits, prefixes)
#  Style  : spotlight/style.css     + colors.css (GENERATED by hyprtheme)
#           + skins/<UI_SKIN>.css   (GENERATED, only for a skin, e.g. "encre")
#  Engines: elephant/websearch.toml (web & maps rows)
#  Actions: elephant/menus/*.toml   (desktop actions rows)
#
#  Keys: ↑/↓ move · Enter open · Shift+Enter alternative (folder / terminal)
#        Ctrl+↓/↑ or Tab next/previous section · Esc or click outside close
#  Run again while open = close (single instance through Gtk.Application).
#  Arguments = initial query, e.g. `spotlight.py :` opens on the clipboard,
#  `spotlight.py . cat` on the emoji.
# =============================================================================
