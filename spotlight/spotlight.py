def menu_commands():
    """text -> shell command, from elephant/menus/*.toml (our desktop actions)."""
    cmds = {}
    d = os.path.join(CFG, "elephant", "menus")
    for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if name.endswith(".toml"):
            for e in load_toml(os.path.join(d, name)).get("entries", []):
                act = (e.get("actions") or {}).get("default")
                if e.get("text") and act:
                    cmds[e["text"]] = act
    return cmds


