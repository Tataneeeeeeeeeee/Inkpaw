def skin_palette():
    """{name: (r, g, b)} from the "@define-color encre_<role> #hex;" lines of the
    skin stylesheet: the colors cairo needs (slanted picture, underlines)."""
    pal = {"encre_ink": "#2a2420", "encre_ochre": "#d9a12e", "encre_paper_dark": "#e2d3b0"}
    try:
        with open(SKIN_CSS, encoding="utf-8") as f:
            pal.update(re.findall(r"@define-color\s+(encre_\w+)\s+(#[0-9a-fA-F]{6})", f.read()))
    except OSError:
        pass
    return {k: tuple(int(v[i:i + 2], 16) / 255 for i in (1, 3, 5)) for k, v in pal.items()}


