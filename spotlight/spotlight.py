def read_settings():
    """KEY="value" pairs of hypr/settings.conf, then of the runtime toggles
    (later wins), exactly like hypr/lib/settings.lua."""
    state = os.path.join(os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state"), "inkpaw")
    vals = {}
    for path in (os.path.join(CFG, "hypr", "settings.conf"), os.path.join(state, "toggles.conf")):
        try:
            with open(path, encoding="utf-8") as f:
                lines = f.read().splitlines()
        except OSError:
            continue
        for line in lines:
            m = re.match(r"\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$", line)
            if not m or line.lstrip().startswith("#"):
                continue
            val = re.sub(r"\s+#.*$", "", m.group(2))              # trailing comment
            if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
                val = val[1:-1]
            vals[m.group(1)] = val
    return vals


