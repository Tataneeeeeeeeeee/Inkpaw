    def draw_slant(self, _area, cr, w, h):
        """encre picture (replaces hyprtheme's menu-side-slant.png, which has a
        white ghost band): the wallpaper crop cut on a slant, an ochre band
        after the cut, both outlined in ink. Geometry of Mew-Main (470 x 470)."""
        ink, ochre = PALETTE["encre_ink"], PALETTE["encre_ochre"]
        iw = w - 60                             # picture width at the top (410)
        cut = h * 48.5 / 470                    # slant of the picture's right edge
        bx, bw, bcut = iw + 6, 29, h * 56 / 470  # the band: x, width, slant
        lw = 3
        # 1. picture (cover-scaled $CACHE/menu-side.png), clipped to the slanted shape
        if self.side_png is None:
            try:
                import cairo
                self.side_png = cairo.ImageSurface.create_from_png(os.path.join(CACHE, "menu-side.png"))
            except Exception:                   # no picture yet / no pycairo: plain paper
                self.side_png = False
        cr.save()
        cr.move_to(0, 0)
        cr.line_to(iw, 0)
        cr.line_to(iw - cut, h)
        cr.line_to(0, h)
        cr.close_path()
        cr.clip()
        img = self.side_png
        if img and img.get_width() and img.get_height():
            k = max(iw / img.get_width(), h / img.get_height())
            cr.translate((iw - img.get_width() * k) / 2, (h - img.get_height() * k) / 2)
            cr.scale(k, k)
            cr.set_source_surface(img, 0, 0)
        else:
            cr.set_source_rgb(*PALETTE["encre_paper_dark"])
        cr.paint()
        cr.restore()
        cr.set_line_width(lw)
        cr.set_line_join(1)                     # cairo.LINE_JOIN_ROUND
        cr.set_line_cap(1)                      # cairo.LINE_CAP_ROUND
        # 2. ochre band, outlined
        cr.move_to(bx, lw / 2)
        cr.line_to(bx + bw, lw / 2)
        cr.line_to(bx + bw - bcut, h - lw / 2)
        cr.line_to(bx - bcut, h - lw / 2)
        cr.close_path()
        cr.set_source_rgb(*ochre)
        cr.fill_preserve()
        cr.set_source_rgb(*ink)
        cr.stroke()
        # 3. ink outline of the picture (open on the left: the card's border is there)
        cr.move_to(0, lw / 2)
        cr.line_to(iw - lw / 2, lw / 2)
        cr.line_to(iw - cut - lw / 2, h - lw / 2)
        cr.line_to(0, h - lw / 2)
        cr.stroke()

    def draw_underline(self, _area, cr, w, h):
        """The hand-drawn ink stroke after a section title, stretched to the width."""
        (x0, y0), *pts = UNDERLINE
        sx, sy = (w - 4) / 196, h / 12
        cr.set_source_rgb(*PALETTE["encre_ink"])
        cr.set_line_width(2)
        cr.set_line_cap(1)                      # round
        cr.move_to(2 + (x0 - 2) * sx, y0 * sy)
        for i in range(0, len(pts), 3):
            (ax, ay), (bx, by), (cx, cy) = pts[i:i + 3]
            cr.curve_to(2 + (ax - 2) * sx, ay * sy, 2 + (bx - 2) * sx, by * sy, 2 + (cx - 2) * sx, cy * sy)
        cr.stroke()

    def build_tabs(self):
        """Chips "All · Files · Emoji · Clipboard · Web": click = type that prefix."""
        box = Gtk.Box(spacing=6)
        box.add_css_class("tabs")
        self.tabs = []
        tabs = [("All", "")] + [(s.get("tab") or s.get("title", s["kind"]).split()[0], s["prefix"])
                                for s in SECTIONS if s.get("prefix") and s["kind"] in TAB_KINDS]
        for name, prefix in tabs:
            chip = Gtk.Label(label=name)
            chip.add_css_class("tab")
            click = Gtk.GestureClick()
            click.connect("pressed", lambda *_a, p=prefix: self.use_prefix(p))
            chip.add_controller(click)
            box.append(chip)
            self.tabs.append((chip, prefix))
        return box

    def use_prefix(self, prefix):
        """Tab clicked: keep the query, swap its prefix."""
        _secs, query = self.active_sections(self.entry.get_text())
        self.entry.set_text(prefix + query)
        self.entry.grab_focus_without_selecting()
        self.entry.set_position(-1)

    def update_tabs(self, text):
        """Highlight the tab of the prefix being used ("All" without prefix)."""
        used = next((s["prefix"] for s in SECTIONS if s.get("prefix") and text.startswith(s["prefix"])), "")
        for chip, prefix in self.tabs:
            (chip.add_css_class if prefix == used else chip.remove_css_class)("active")

    def emoji_grid_row(self, rows):
        """encre: the emoji of a search as a grid of small ink cards, in ONE list
        row. ←/→ (and ↑/↓ inside the grid) move the current card; row.data is
        the current emoji, so Enter / Shift+Enter / click work like any row."""
        cols = max(4, (int(CONF.get("list_width", 420)) - 56) // 46)
        row = Gtk.ListBoxRow()
        row.add_css_class("emoji-grid")
        row.add_css_class("kind-emoji")
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
        grid = Gtk.Grid(column_spacing=6, row_spacing=6)
        row.cells, row.items, row.cols, row.cell = [], rows, cols, 0
        for i, r in enumerate(rows):
            cell = Gtk.Label(label=r["glyph"], tooltip_text=r["title"])
            cell.add_css_class("emoji-cell")
            cell.add_css_class(("tilt-l", "", "tilt-r")[i % 3] or "tilt-0")
            click = Gtk.GestureClick()          # the click then activates the row
            click.connect("pressed", lambda *_a, i=i: self.set_cell(row, i))
            cell.add_controller(click)
            grid.attach(cell, i % cols, i // cols, 1, 1)
            row.cells.append(cell)
        row.caption = Gtk.Label(xalign=0, ellipsize=3)
        row.caption.add_css_class("emoji-name")
        box.append(grid)
        box.append(row.caption)
        row.set_child(box)
        row.is_header = False
        self.set_cell(row, 0)
        return row

    def set_cell(self, row, i):
        row.cells[row.cell].remove_css_class("current")
        row.cell = i
        row.cells[i].add_css_class("current")
        row.data = row.items[i]
        row.caption.set_label(f"{row.data['title']}  ·  ↵ insert  ·  ⇧↵ copy")

    def grid_key(self, keyval):
        """←/→/↑/↓ inside the selected emoji grid; False = not handled."""
        row = self.list.get_selected_row()
        if not hasattr(row, "cells"):
            return False
        n, c, cols = len(row.cells), row.cell, row.cols
        if keyval == Gdk.KEY_Left:
            target = max(0, c - 1)
        elif keyval == Gdk.KEY_Right:
            target = min(n - 1, c + 1)
        elif keyval == Gdk.KEY_Down and c // cols < (n - 1) // cols:
            target = min(n - 1, c + cols)
        elif keyval == Gdk.KEY_Up and c >= cols:
            target = c - cols
        else:
            return False                        # ↑/↓ on the first/last line: leave the grid
        self.set_cell(row, target)
        return True

    # --- navigation ---
    def rows(self):
        out, i = [], 0
        while (row := self.list.get_row_at_index(i)) is not None:
            out.append(row)
            i += 1
        return out

    def move(self, step, by_section=False):
        """Select the next/previous item; by_section jumps to the first item of
        the next/previous section."""
        rows = self.rows()
        items = [i for i, r in enumerate(rows) if not getattr(r, "is_header", True)]
        if not items:
            return
        cur = self.list.get_selected_row()
        idx = rows.index(cur) if cur in rows else items[0]
        if by_section:
            firsts = [i for i in items if i > 0 and getattr(rows[i - 1], "is_header", False)]
            mine = max([f for f in firsts if f <= idx], default=firsts[0])
            pos = firsts.index(mine) + (1 if step > 0 else -1)
            target = firsts[pos % len(firsts)]
        else:
            pos = items.index(idx) + step if idx in items else 0
            if pos < 0 or pos >= len(items):
                return
            target = items[pos]
        row = rows[target]
        self.list.select_row(row)
        self.scroll_to(row)

    def scroll_to(self, row):
        """Keep the selected row visible while the focus stays in the entry."""
        adj = self.scroll.get_vadjustment()
        ok, rect = row.compute_bounds(self.list)
        if not ok:
            return
        top, bottom = rect.get_y(), rect.get_y() + rect.get_height()
        if top < adj.get_value():
            adj.set_value(max(0, top - 30))      # 30 px: show the section title too
        elif bottom + 12 > adj.get_value() + adj.get_page_size():
            adj.set_value(min(adj.get_upper() - adj.get_page_size(), bottom + 12 - adj.get_page_size()))

    def on_key(self, _ctl, keyval, _code, state):
        ctrl = state & Gdk.ModifierType.CONTROL_MASK
        shift = state & Gdk.ModifierType.SHIFT_MASK
        if keyval == Gdk.KEY_Escape:
            self.quit()
        elif ENCRE and not ctrl and keyval in (Gdk.KEY_Left, Gdk.KEY_Right, Gdk.KEY_Up, Gdk.KEY_Down) \
                and self.grid_key(keyval):
            pass
        elif keyval in (Gdk.KEY_Down, Gdk.KEY_Up):
            self.move(1 if keyval == Gdk.KEY_Down else -1, by_section=bool(ctrl))
        elif keyval in (Gdk.KEY_Tab, Gdk.KEY_ISO_Left_Tab):
            self.move(-1 if (shift or keyval == Gdk.KEY_ISO_Left_Tab) else 1, by_section=True)
        elif keyval in (Gdk.KEY_Return, Gdk.KEY_KP_Enter) and shift:
            self.activate_selected(True)
        else:
            return False
        return True

    def activate_selected(self, alt):
        row = self.list.get_selected_row()
        if row is not None:
            self.activate_row(row, alt)

    def activate_row(self, row, alt):
        data = getattr(row, "data", None)
        if not data:
            return
        action = data.get("alt") if alt and data.get("alt") else data["action"]
        self.win.set_visible(False)
        run_action(action)
        GLib.timeout_add(150, self.quit)


