#!/usr/bin/env bash
# =============================================================================
#  session/start.sh — start a REAL Hyprland session with inkpaw
# =============================================================================
#  Launched by SDDM through /usr/share/wayland-sessions/inkpaw.desktop
#  (installed by session/install.sh). Your own ~/.config is never modified.
#
#  How: a "merged" config root is rebuilt at every login in
#      ~/.local/share/inkpaw/session-root
#  containing
#    * symlinks to THIS project for its folders (hypr, hyprtheme, waybar…,
#      see OURS below)                  → live edits, no copy step
#    * symlinks to your real ~/.config/<entry> for everything else
#      (browser, nvim, discord… keep their settings)
#    * real folders for gtk-3.0, gtk-4.0 and kitty: each file symlinked to the
#      original, except the files the theme engine generates (gtk.css,
#      kitty.conf + inkpaw-theme.conf), so your own files are never overwritten.
#  Then XDG_CONFIG_HOME points to it and Hyprland is started via start-hyprland.
#
#  Log: ~/.local/share/inkpaw/session.log
# =============================================================================
set -u

PROJECT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
REAL="$HOME/.config"
BASE="${XDG_DATA_HOME:-$HOME/.local/share}/inkpaw"
ROOT="$BASE/session-root"
LOG="$BASE/session.log"

# Folders served from this project
OURS=(hypr hyprtheme waybar walker elephant swaync rofi wlogout swayosd spotlight settings-app quickpanel aichat deskpet welcome powermenu keysheet themepicker wallpicker)
# Folders merged file-by-file (some files generated by the theme engine)
MERGED=(gtk-3.0 gtk-4.0 kitty)
# Generated files that must NOT point to the originals
GENERATED=(gtk-3.0/gtk.css gtk-4.0/gtk.css kitty/kitty.conf kitty/inkpaw-theme.conf kitty/inkpaw-settings.conf)

mkdir -p "$BASE"
exec >>"$LOG" 2>&1
echo "=== $(date '+%F %T') inkpaw session (project: $PROJECT)"

in_list() { local x="$1"; shift; for e in "$@"; do [ "$e" = "$x" ] && return 0; done; return 1; }

# 1. Anything an app created as a REAL folder/file inside the root during the
#    last session belongs in ~/.config: move it there (never overwrite).
if [ -d "$ROOT" ]; then
    for p in "$ROOT"/* "$ROOT"/.[!.]*; do
        [ -e "$p" ] || continue
        n="$(basename "$p")"
        [ -L "$p" ] && continue
        in_list "$n" "${OURS[@]}" "${MERGED[@]}" && continue
        if [ ! -e "$REAL/$n" ]; then mv "$p" "$REAL/$n" && echo "moved new entry $n to ~/.config"; fi
    done
fi

# 2. Rebuild the root
rm -rf "$ROOT.new"; mkdir -p "$ROOT.new"
for p in "$REAL"/* "$REAL"/.[!.]*; do
    [ -e "$p" ] || [ -L "$p" ] || continue
    n="$(basename "$p")"
    in_list "$n" "${OURS[@]}" "${MERGED[@]}" && continue
    ln -s "$REAL/$n" "$ROOT.new/$n"
done
for n in "${OURS[@]}"; do ln -s "$PROJECT/$n" "$ROOT.new/$n"; done
for d in "${MERGED[@]}"; do
    mkdir -p "$ROOT.new/$d"
    [ -d "$REAL/$d" ] || continue
    for f in "$REAL/$d"/* "$REAL/$d"/.[!.]*; do
        [ -e "$f" ] || continue
        rel="$d/$(basename "$f")"
        in_list "$rel" "${GENERATED[@]}" && continue
        ln -s "$f" "$ROOT.new/$rel"
    done
done

# Keep the previously generated files (palette survives the rebuild)
for g in "${GENERATED[@]}"; do
    [ -f "$ROOT/$g" ] && [ ! -L "$ROOT/$g" ] && cp "$ROOT/$g" "$ROOT.new/$g"
done
# kitty: your kitty.conf + the generated theme + generated settings (always rewritten)
rm -f "$ROOT.new/kitty/kitty.conf"
{
    echo "# inkpaw session: your kitty.conf + generated theme + settings window values"
    [ -f "$REAL/kitty/kitty.conf" ] && echo "include $REAL/kitty/kitty.conf"
    echo "include inkpaw-theme.conf"
    echo "include inkpaw-settings.conf"
} >"$ROOT.new/kitty/kitty.conf"
[ -f "$ROOT.new/kitty/inkpaw-theme.conf" ] || cp "$PROJECT/kitty/inkpaw-theme.conf" "$ROOT.new/kitty/"

rm -rf "$ROOT"; mv "$ROOT.new" "$ROOT"

# 3. Start Hyprland on the merged root
export XDG_CONFIG_HOME="$ROOT"
unset INKPAW_TEST
echo "XDG_CONFIG_HOME=$XDG_CONFIG_HOME"
exec /usr/bin/start-hyprland -- -c "$ROOT/hypr/hyprland.lua"
