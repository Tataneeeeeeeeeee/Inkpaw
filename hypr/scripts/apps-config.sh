#!/usr/bin/env bash
# =============================================================================
#  apps-config.sh — apply the "Applications" settings (settings window page)
# =============================================================================
#  Usage: apps-config.sh [KEY]     KEY = the setting that just changed (optional)
#
#  • kitty: KITTY_FONT, KITTY_FONT_SIZE, KITTY_OPACITY, KITTY_PADDING,
#    KITTY_CURSOR are written to kitty/inkpaw-settings.conf (empty value
#    = keep what your kitty.conf says), then running kittys reload (SIGUSR1).
#  • BROWSER / FILEMANAGER: registered as the system default (xdg-settings /
#    xdg-mime) for web links and folders — only when that key changed.
#  • FILES_SHOW_HIDDEN / FILES_VIEW: GTK file chooser + Nautilus preferences.
#  Other app keys (TERMINAL, EDITOR_GUI…) are read directly by the keybinds.
# =============================================================================
. "$(dirname "$(readlink -f "$0")")/lib.sh"

changed="${1:-all}"

# --- kitty ---------------------------------------------------------------------------
kitty_settings() {
    local out="$CFG/kitty/inkpaw-settings.conf"
    mkdir -p "$CFG/kitty"
    {
        echo "# GENERATED by hypr/scripts/apps-config.sh from settings (Applications → Terminal)."
        echo "# Included by kitty.conf after your own settings; empty settings are not written."
        [ -n "${KITTY_FONT:-}" ]      && echo "font_family $KITTY_FONT"
        [ -n "${KITTY_FONT_SIZE:-}" ] && echo "font_size $KITTY_FONT_SIZE"
        [ -n "${KITTY_OPACITY:-}" ]   && { echo "background_opacity $KITTY_OPACITY"; echo "dynamic_background_opacity yes"; }
        [ -n "${KITTY_PADDING:-}" ]   && echo "window_padding_width $KITTY_PADDING"
        [ -n "${KITTY_CURSOR:-}" ]    && echo "cursor_shape $KITTY_CURSOR"
    } >"$out"
    pkill -USR1 -x kitty 2>/dev/null || true
}

# --- default apps (xdg) ----------------------------------------------------------------
# .desktop file whose Exec starts with the given command
desktop_for() {
    local bin="${1%% *}" f dir
    for dir in "${XDG_DATA_HOME:-$HOME/.local/share}/applications" /usr/share/applications \
               /var/lib/flatpak/exports/share/applications; do
        for f in "$dir"/*.desktop; do
            [ -f "$f" ] || continue
            if grep -qE "^Exec=(/usr/bin/)?$bin( |$)" "$f"; then basename "$f"; return; fi
        done
    done
}

set_browser() {
    local d; d=$(desktop_for "${BROWSER:-firefox}")
    [ -n "$d" ] && xdg-settings set default-web-browser "$d" 2>/dev/null && notify "Default browser" "$d"
}

set_filemanager() {
    local d; d=$(desktop_for "${FILEMANAGER:-nautilus}")
    [ -n "$d" ] && xdg-mime default "$d" inode/directory && notify "Folders open with" "$d"
}

# --- file manager preferences -------------------------------------------------------------
files_prefs() {
    have gsettings || return 0
    if [ -n "${FILES_SHOW_HIDDEN:-}" ]; then
        local v=false; is_true FILES_SHOW_HIDDEN false && v=true
        gsettings set org.gtk.gtk4.Settings.FileChooser show-hidden "$v" 2>/dev/null
        gsettings set org.gtk.Settings.FileChooser show-hidden "$v" 2>/dev/null
        gsettings set org.gnome.nautilus.preferences show-hidden-files "$v" 2>/dev/null
    fi
    case "${FILES_VIEW:-}" in
        list) gsettings set org.gnome.nautilus.preferences default-folder-viewer list-view 2>/dev/null ;;
        grid) gsettings set org.gnome.nautilus.preferences default-folder-viewer icon-view 2>/dev/null ;;
    esac
}

is_test && { kitty_settings; exit 0; }     # never touch system defaults from ./test.sh

case "$changed" in
    KITTY_*)                      kitty_settings ;;
    BROWSER)                      set_browser ;;
    FILEMANAGER)                  set_filemanager ;;
    FILES_SHOW_HIDDEN|FILES_VIEW) files_prefs ;;
    all)                          kitty_settings ;;     # at login: only the kitty file
esac
