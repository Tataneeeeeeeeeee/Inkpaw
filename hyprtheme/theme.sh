#!/usr/bin/env bash
# =============================================================================
#  hyprtheme/theme.sh — wallpaper + dynamic theming engine (matugen)
# =============================================================================
#  Usage:
#    theme.sh wallpaper <image>     set wallpaper (awww/swww) + palette from it
#    theme.sh random                random image from WALLPAPER_DIR
#    theme.sh static <name>         palette from hyprtheme/static/<name>.json
#    theme.sh mode dark|light|toggle
#    theme.sh scheme <matugen-scheme>
#    theme.sh restore               re-apply the last theme (used at login)
#    theme.sh current               print the saved state
#    theme.sh list-static           list static themes
#
#  How it works
#    * Every file in hyprtheme/templates/ is a matugen template. Its first lines
#      contain "@output: <path relative to the config root>" (or
#      "@output: cache:<path>" for a file under ~/.cache, e.g. pywal colors). This script builds
#      a matugen config from those headers, so ADDING A THEMED APP = ADDING ONE
#      TEMPLATE FILE. Move a template to templates/disabled/ to switch it off.
#    * UI tokens (font, radius, opacity…) from settings.conf are injected as
#      {{ui.*}} in every template.
#    * After rendering, every hooks/*.sh is run to live-reload the apps.
#    * State (source, wallpaper, static name) is persisted in
#      ~/.local/state/inkpaw/theme.conf.
#
#  Env switches (used by ./test.sh):
#    THEME_NO_RELOAD=1     render files only, run no hook
#    THEME_NO_WALLPAPER=1  never touch the wallpaper daemon
# =============================================================================
set -uo pipefail
. "${XDG_CONFIG_HOME:-$HOME/.config}/hypr/scripts/lib.sh"

THEME_STATE="$STATE/theme.conf"
MATUGEN_CONF="$CACHE/matugen.toml"
TEMPLATES="$THEME_DIR/templates"
STATIC_DIR="$THEME_DIR/static"

# Saved state ---------------------------------------------------------------
THEME_SOURCE=""; THEME_WALLPAPER=""; THEME_STATIC=""
# shellcheck disable=SC1090
[ -f "$THEME_STATE" ] && . "$THEME_STATE"

save_state() {
    cat >"$THEME_STATE" <<EOF
# Written by hyprtheme/theme.sh — last applied theme
THEME_SOURCE="$THEME_SOURCE"
THEME_WALLPAPER="$THEME_WALLPAPER"
THEME_STATIC="$THEME_STATIC"
EOF
}

die() { echo "theme.sh: $*" >&2; notify "Theme" "$*"; exit 1; }

# UI tokens -> JSON for {{ui.*}} ----------------------------------------------
ui_json() {
    local op="${UI_OPACITY:-0.88}"
    local op_hex; op_hex=$(awk -v o="$op" 'BEGIN { printf "%02x", int(o * 255 + 0.5) }')
    jq -cn --arg font "${FONT_FAMILY:-sans-serif}" --arg icon_font "${ICON_FONT:-Symbols Nerd Font}" \
           --arg size "${FONT_SIZE:-13}" \
           --arg radius "${UI_RADIUS:-12}" --arg border "${UI_BORDER:-2}" \
           --arg opacity "$op" --arg opacity_hex "$op_hex" \
           --arg rounding "${ROUNDING:-10}" --arg side "$SIDE_IMAGE" \
           --arg wallpaper "${SIDE_SRC:-${THEME_WALLPAPER:-}}" \
           --arg slant "$SLANT_IMAGE" --arg mono "${MONO_FONT:-monospace}" \
           --arg display "${DISPLAY_FONT:-${FONT_FAMILY:-sans-serif}}" --arg skin "${UI_SKIN:-default}" \
           --arg skin_dir "$THEME_DIR/skins/${UI_SKIN:-default}" \
        '{ui: {font: $font, icon_font: $icon_font, font_size: $size, radius: $radius, border: $border,
               opacity: $opacity, opacity_hex: $opacity_hex, rounding: $rounding, side_image: $side,
               wallpaper: $wallpaper, slant_image: $slant, mono_font: $mono,
               display_font: $display, skin: $skin, skin_dir: $skin_dir}}'
}

# Build matugen.toml from the @output headers of every template -----------------
build_config() {
    {
        echo "# GENERATED by hyprtheme/theme.sh from templates/*/ @output headers"
        echo "[config]"
        echo "version_check = false"
        echo "[templates]"
        local t name out
        for t in "$TEMPLATES"/*; do
            [ -f "$t" ] || continue
            out=$(head -n 5 "$t" | sed -n 's/.*@output:[[:space:]]*\([^[:space:]*]*\).*/\1/p' | head -1)
            [ -z "$out" ] && { echo "# skipped $(basename "$t"): no @output header"; continue; }
            name=$(basename "$t" | tr -c 'a-zA-Z0-9_\n' '_')
            # "cache:path" = relative to ~/.cache (e.g. pywal's colors.json), else to the config root
            local dest="$CFG/$out"
            [[ "$out" == cache:* ]] && dest="${XDG_CACHE_HOME:-$HOME/.cache}/${out#cache:}"
            mkdir -p "$(dirname "$dest")"
            printf "[templates.%s]\ninput_path = '%s'\noutput_path = '%s'\n" "$name" "$t" "$dest"
        done
    } >"$MATUGEN_CONF"
}

run_hooks() {
    [ "${THEME_NO_RELOAD:-0}" = "1" ] && return 0
    local h
    for h in "$THEME_DIR"/hooks/*.sh; do
        [ -x "$h" ] && "$h" >/dev/null 2>&1 &
    done
    wait
}

mode() { echo "${THEME_MODE:-dark}"; }
scheme() { echo "${MATUGEN_SCHEME:-scheme-tonal-spot}"; }

# Wallpaper daemon -------------------------------------------------------------
set_wallpaper() {
    [ "${THEME_NO_WALLPAPER:-0}" = "1" ] && return 0
    local bin=""
    have awww && bin=awww
    [ -z "$bin" ] && have swww && bin=swww
    [ -z "$bin" ] && { echo "no awww/swww: wallpaper not set" >&2; return 0; }
    # Wait up to 3 s for the daemon (it may still be starting at login)
    local i; for i in $(seq 30); do "$bin" query >/dev/null 2>&1 && break; sleep 0.1; done
    "$bin" img "$1" \
        --transition-type "${WALLPAPER_TRANSITION:-grow}" \
        --transition-duration "${WALLPAPER_TRANSITION_DURATION:-1.2}" \
        --transition-fps "${WALLPAPER_TRANSITION_FPS:-60}" >/dev/null 2>&1
}

# Palette generators -------------------------------------------------------------
#  Every source produces a matugen "dump" (JSON palette). render() then adds the
#  UI tokens + 6 accent colors and renders every template from that dump.

# Side picture shown in the rofi menus (HyDE-style): a portrait crop of the
# current wallpaper, or an accent gradient when there is no wallpaper.
SIDE_IMAGE="$CACHE/menu-side.png"
make_side_image() {   # <accents-json>
    local src="${SIDE_SRC:-$THEME_WALLPAPER}"
    if [ -n "$src" ] && [ -f "$src" ]; then
        magick "${src}[0]" -resize x1000^ -gravity center -crop 640x1000+0+0 +repage "$SIDE_IMAGE" 2>/dev/null && return
    fi
    local c1 c2 c3
    c1=$(jq -r '.accent.a1' <<<"$1"); c2=$(jq -r '.accent.a3' <<<"$1"); c3=$(jq -r '.accent.a5' <<<"$1")
    magick -size 160x250 "gradient:$c1-$c2" \( -size 160x250 "radial-gradient:${c3}cc-none" \) \
        -gravity southeast -composite -blur 0x6 -resize 640x1000! "$SIDE_IMAGE" 2>/dev/null || true
}

# HyDE-style picture for the Spotlight: the side picture cut on a slant, with
# a faint "ghost" band after the cut (spotlight/style.css .side-slant).
SLANT_IMAGE="$CACHE/menu-side-slant.png"
make_slant_image() {
    [ -f "$SIDE_IMAGE" ] || return 0
    local w=400 h=460 cut=46 ghost=56
    magick "$SIDE_IMAGE" -resize "${w}x${h}^" -gravity center -extent "${w}x${h}" "$CACHE/.slant-src.png" 2>/dev/null || return 0
    magick -size "$((w + ghost))x${h}" xc:none \
        \( "$CACHE/.slant-src.png" \( -size "${w}x${h}" xc:black -fill white \
              -draw "polygon 0,0 $w,0 $((w - cut)),$h 0,$h" \) -alpha off -compose copyopacity -composite \) \
        -gravity northwest -compose over -composite \
        -fill "rgba(255,255,255,0.16)" -draw "polygon $((w + 4)),0 $((w + ghost)),0 $((w + ghost - cut)),$h $((w - cut + 4)),$h" \
        "$SLANT_IMAGE" 2>/dev/null
    rm -f "$CACHE/.slant-src.png"
}

# render <dump.json> <mode> [static-theme.json]
render() {
    local dump="$1" m="$2" static="${3:-}" primary explicit="" extra acc
    primary=$(jq -r '.colors.primary.default.color' "$dump")
    [ -n "$static" ] && explicit=$(jq -r '(.accents // []) | join(",")' "$static")
    acc=$(python3 -I "$THEME_DIR/lib/accents.py" "$primary" "$m" "$explicit" "${ACCENT_STYLE:-wallbash}")
    make_side_image "$acc"
    make_slant_image
    extra=$(jq -cn --argjson a "$acc" --argjson u "$(ui_json)" '$u + $a')
    matugen json "$dump" -c "$MATUGEN_CONF" -m "$m" --import-json-string "$extra" -q
}

gen_from_image() {
    build_config
    local dump="$CACHE/palette.json"
    matugen image "$1" -c "$MATUGEN_CONF" -m "$(mode)" -t "$(scheme)" \
        --prefer "${MATUGEN_PREFER:-saturation}" --dry-run -j hex >"$dump" 2>/dev/null || die "matugen failed on $1"
    render "$dump" "$(mode)" || die "rendering failed for $1"
}

# Seed color only (static theme without a light/dark sibling)
gen_from_seed() {   # <hex> <mode>
    build_config
    local dump="$CACHE/palette.json"
    matugen color hex "$1" -c "$MATUGEN_CONF" -m "$2" -t "$(scheme)" --dry-run -j hex >"$dump" 2>/dev/null || die "matugen failed on $1"
    render "$dump" "$2"
}

# Static theme: hand-written palette overlaid on a matugen palette generated
# from the theme's seed color (so every Material role always exists).
gen_from_static() {
    local file="$STATIC_DIR/$1.json"
    [ -f "$file" ] || die "unknown static theme '$1'"
    build_config
    local seed smode dump="$CACHE/palette.json"
    seed=$(jq -r '.seed' "$file")
    smode=$(jq -r '.mode // "dark"' "$file")
    matugen color hex "$seed" -c "$MATUGEN_CONF" -m "$smode" -t "$(scheme)" --dry-run -j hex 2>/dev/null |
        jq --slurpfile t "$file" --arg mode "$smode" '
            .mode = $mode | .is_dark_mode = ($mode == "dark")
            | .colors |= reduce ($t[0].colors | to_entries[]) as $e (.;
                  .[$e.key] = { dark: {color: $e.value}, default: {color: $e.value}, light: {color: $e.value} })
        ' >"$dump" || die "could not build palette for $1"
    render "$dump" "$smode" "$file" || die "rendering failed for static theme $1"
}

# Commands ------------------------------------------------------------------------
apply_wallpaper() {
    local wp; wp=$(readlink -f "$1") || die "no such file: $1"
    [ -f "$wp" ] || die "no such file: $1"
    set_wallpaper "$wp"
    SIDE_SRC="$wp" gen_from_image "$wp"
    THEME_SOURCE="wallpaper"; THEME_WALLPAPER="$wp"; save_state
    run_hooks
}

# Wallpaper bundled with a static theme ("wallpaper" in its JSON), if present
static_wallpaper() {
    local f; f=$(jq -r '.wallpaper // empty' "$STATIC_DIR/$1.json" 2>/dev/null)
    [ -n "$f" ] && [ -f "${WALLPAPER_DIR:-$HOME/Pictures/wallpapers}/$f" ] && echo "${WALLPAPER_DIR:-$HOME/Pictures/wallpapers}/$f"
}

apply_static() {
    local wp; wp=$(static_wallpaper "$1")
    if [ -n "$wp" ]; then set_wallpaper "$wp"; THEME_WALLPAPER="$wp"; fi
    SIDE_SRC="${wp:-$THEME_WALLPAPER}" gen_from_static "$1"
    THEME_SOURCE="static"; THEME_STATIC="$1"; save_state
    # A static theme is light or dark by definition: keep THEME_MODE in sync
    state_set THEME_MODE "$(jq -r '.mode // "dark"' "$STATIC_DIR/$1.json")"
    run_hooks
}

regenerate() {   # re-render from the saved source (after mode / scheme change)
    case "$THEME_SOURCE" in
        wallpaper) gen_from_image "$THEME_WALLPAPER" ;;
        static)    gen_from_static "$THEME_STATIC" ;;
        *)         gen_from_static "${DEFAULT_STATIC_THEME:-catppuccin-mocha}"
                   THEME_SOURCE="static"; THEME_STATIC="${DEFAULT_STATIC_THEME:-catppuccin-mocha}"; save_state ;;
    esac
    run_hooks
}

cmd_mode() {
    local want="$1" cur; cur=$(mode)
    [ "$want" = "toggle" ] && { [ "$cur" = "dark" ] && want=light || want=dark; }
    [[ "$want" == dark || "$want" == light ]] || die "mode must be dark|light|toggle"
    state_set THEME_MODE "$want"; THEME_MODE="$want"
    if [ "$THEME_SOURCE" = "static" ]; then
        # Static themes declare their light/dark sibling with "pair"
        local pair; pair=$(jq -r '.pair // empty' "$STATIC_DIR/$THEME_STATIC.json" 2>/dev/null)
        if [ -n "$pair" ] && [ "$(jq -r .mode "$STATIC_DIR/$pair.json")" = "$want" ]; then
            apply_static "$pair"; notify "Theme" "$want mode"; return
        fi
        # No sibling: Material palette from the static theme's seed color
        gen_from_seed "$(jq -r .seed "$STATIC_DIR/$THEME_STATIC.json")" "$want"
        run_hooks
    else
        regenerate
    fi
    notify "Theme" "$want mode"
}

cmd_random() {
    local dir="${WALLPAPER_DIR:-$HOME/Pictures/wallpapers}" wp
    wp=$(find -L "$dir" -maxdepth 2 -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.gif' \) \
         ! -path "$THEME_WALLPAPER" 2>/dev/null | shuf -n 1)
    [ -n "$wp" ] || die "no images in $dir"
    apply_wallpaper "$wp"
}

cmd_restore() {
    case "$THEME_SOURCE" in
        wallpaper)
            if [ -f "$THEME_WALLPAPER" ]; then set_wallpaper "$THEME_WALLPAPER"; gen_from_image "$THEME_WALLPAPER"
            else THEME_SOURCE=""; regenerate; return; fi ;;
        static)    [ -f "$THEME_WALLPAPER" ] && set_wallpaper "$THEME_WALLPAPER"
                   gen_from_static "$THEME_STATIC" ;;
        *)         regenerate; return ;;
    esac
    run_hooks
}

case "${1:-}" in
    wallpaper)   apply_wallpaper "${2:?image path required}" ;;
    random)      cmd_random ;;
    static)      apply_static "${2:?static theme name required}" ;;
    mode)        cmd_mode "${2:-toggle}" ;;
    scheme)      state_set MATUGEN_SCHEME "${2:?scheme required}"; MATUGEN_SCHEME="$2"; regenerate ;;
    restore)     cmd_restore ;;
    current)     cat "$THEME_STATE" 2>/dev/null; echo "THEME_MODE=$(mode)"; echo "MATUGEN_SCHEME=$(scheme)" ;;
    list-static) for f in "$STATIC_DIR"/*.json; do printf '%s\t%s\n' "$(basename "$f" .json)" "$(jq -r '.name + " (" + .mode + ")"' "$f")"; done ;;
    *) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
